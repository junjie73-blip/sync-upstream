/**
 * Shell completion scripts, generated from the CLI's own flag tables.
 *
 * The point of generating instead of hand-writing a script is that there is then exactly one
 * place that knows what switches exist: `src/cli.ts`. A new flag lands in tab-completion the
 * moment it is added to the table it was already added to, and a checked-in script cannot
 * quietly drift away from `--help`.
 *
 * Bash is exercised by the test suite (the generated function is sourced and called with a
 * simulated `COMP_WORDS`); zsh and fish follow the same data but are only syntax-guarded here,
 * so they stay deliberately simple.
 */
export const COMPLETION_SHELLS = ['bash', 'zsh', 'fish'] as const

export type CompletionShell = typeof COMPLETION_SHELLS[number]

export function isCompletionShell(value: string): value is CompletionShell {
  return (COMPLETION_SHELLS as readonly string[]).includes(value)
}

export interface CompletionSource {
  /** Flags that take a value (`--repo <url>`). */
  stringFlags: readonly string[]
  /** Switches that stand alone. */
  booleanFlags: readonly string[]
  /** Both spellings of the negatable switches, e.g. `delete` and `no-delete`. */
  negatableFlags: readonly string[]
  /** Short aliases as `letter -> long`. */
  aliases: Readonly<Record<string, string>>
  /** Read-only subcommands. */
  subcommands: readonly string[]
  /** Verbs the CLI handles itself, e.g. `init`, `completion`. */
  verbs: readonly string[]
  /** One-liners keyed by command name, already in the requested language. */
  descriptions: Record<string, string>
}

interface FlagSpec {
  long: string
  short?: string
  takesValue: boolean
}

function flagSpecs(source: CompletionSource): FlagSpec[] {
  const shorts = new Map<string, string>()
  for (const [short, long] of Object.entries(source.aliases)) {
    if (!shorts.has(long))
      shorts.set(long, short)
  }

  const specs: FlagSpec[] = []
  const seen = new Set<string>()
  const push = (long: string, takesValue: boolean): void => {
    if (seen.has(long))
      return
    seen.add(long)
    specs.push({ long, short: shorts.get(long), takesValue })
  }
  for (const long of source.stringFlags)
    push(long, true)
  for (const long of source.booleanFlags)
    push(long, false)
  for (const long of source.negatableFlags)
    push(long, false)
  return specs.sort((a, b) => a.long.localeCompare(b.long))
}

/** `--long` for every flag, plus the `-x` spelling where one exists. */
function allFlagTokens(source: CompletionSource): string[] {
  const tokens: string[] = []
  for (const spec of flagSpecs(source)) {
    tokens.push(`--${spec.long}`)
    if (spec.short)
      tokens.push(`-${spec.short}`)
  }
  return tokens
}

/** The tokens after which a value — a URL, a path — is expected instead of another flag. */
function valueFlagTokens(source: CompletionSource): string[] {
  const tokens: string[] = []
  for (const spec of flagSpecs(source)) {
    if (!spec.takesValue)
      continue
    tokens.push(`--${spec.long}`)
    if (spec.short)
      tokens.push(`-${spec.short}`)
  }
  return tokens
}

function commandTokens(source: CompletionSource): string[] {
  return [...source.subcommands, ...source.verbs]
}

function description(source: CompletionSource, name: string): string {
  // A stray apostrophe would end the quoted hint early and break the whole script; the
  // descriptions are ours, so dropping the character is cheaper than escaping it per shell.
  return (source.descriptions[name] ?? name).replace(/'/g, '')
}

/**
 * The script for one shell, ready to be redirected into a completions directory.
 *
 * The header names the command that produced it, so an operator regenerating a stale file knows
 * exactly what to run again.
 */
export function completionScript(shell: CompletionShell, source: CompletionSource): string {
  const header = `# Generated by sync-upstream. Regenerate with: sync-upstream completion ${shell}`
  if (shell === 'bash')
    return bashScript(source, header)
  if (shell === 'zsh')
    return zshScript(source, header)
  return fishScript(source, header)
}

function bashScript(source: CompletionSource, header: string): string {
  const flags = allFlagTokens(source).join(' ')
  const valueFlags = valueFlagTokens(source).join(' ')
  const commands = commandTokens(source).join(' ')
  return `${header}
_sync_upstream() {
  local cur prev word subcommand='' skip_value=0
  cur="\${COMP_WORDS[COMP_CWORD]}"
  prev="\${COMP_WORDS[COMP_CWORD-1]}"

  # 第一个既不是选项、也不是某个选项取值的词，才是子命令。
  local i
  for ((i = 1; i < COMP_CWORD; i++)); do
    word="\${COMP_WORDS[i]}"
    if (( skip_value )); then skip_value=0; continue; fi
    if [[ "\${word}" == -* ]]; then
      case " ${valueFlags} " in *" \${word%%=*} "*) skip_value=1 ;; esac
      continue
    fi
    if [[ -z "\$subcommand" ]]; then subcommand="\$word"; fi
  done

  # 刚敲完一个要取值的选项：该接 URL 或路径，交给 -o default 的文件补全。
  # 注意"取值已经打完"的下一步（-r <url> <TAB>）不在这里拦：那时候选词是空串，
  # 用户要的是下一个参数，光标真的停在 URL 中间时 bash 会把 URL 当成当前词传进来。
  case " ${valueFlags} " in
    *" \${prev%%=*} "*) COMPREPLY=(); return 0 ;;
  esac

  if [[ "\$subcommand" == completion ]]; then
    COMPREPLY=( \$(compgen -W "bash zsh fish" -- "\$cur") )
    return 0
  fi
  if [[ "\$cur" == -* ]]; then
    COMPREPLY=( \$(compgen -W "${flags}" -- "\$cur") )
    return 0
  fi
  if [[ -z "\$subcommand" ]]; then
    COMPREPLY=( \$(compgen -W "${commands} ${flags}" -- "\$cur") )
    return 0
  fi
  COMPREPLY=( \$(compgen -W "${flags}" -- "\$cur") )
}

# -o default：why <文件路径> 这类位置参数落回普通文件补全。
complete -o default -F _sync_upstream sync-upstream
`
}

function zshScript(source: CompletionSource, header: string): string {
  const flags = allFlagTokens(source).map(token => `'${token}'`).join(' ')
  const valueFlags = valueFlagTokens(source).map(token => `'${token}'`).join(' ')
  const commands = commandTokens(source)
    .map(name => `'${name}:${description(source, name)}'`)
    .join(' ')
  return `${header}
#compdef sync-upstream

_sync_upstream() {
  local -a commands flags value_flags
  commands=(${commands})
  flags=(${flags})
  value_flags=(${valueFlags})

  if [[ "\${words[2]}" == completion ]]; then
    _values 'shell' bash zsh fish
    return
  fi

  # 取值型选项后面交给文件/URL 补全，不要再列 flag。
  if [[ " \${value_flags} " == *" \${words[CURRENT-1]} "* ]]; then
    _files
    return
  fi

  if (( CURRENT == 2 )); then
    _describe -t commands 'sync-upstream command' commands
  fi
  compadd -a flags
  _files
}

_sync_upstream "\$@"
`
}

function fishScript(source: CompletionSource, header: string): string {
  const lines = [header]
  for (const spec of flagSpecs(source)) {
    const parts = ['complete', '-c', 'sync-upstream', '-l', spec.long]
    if (spec.short)
      parts.push('-s', spec.short)
    // -r 告诉 fish 这个选项还要接一个取值。
    if (spec.takesValue)
      parts.push('-r')
    lines.push(parts.join(' '))
  }
  for (const name of commandTokens(source))
    lines.push(`complete -c sync-upstream -f -n '__fish_use_subcommand' -a '${name}' -d '${description(source, name)}'`)
  lines.push(`complete -c sync-upstream -f -n '__fish_seen_subcommand_from completion' -a 'bash zsh fish'`)
  lines.push(`complete -c sync-upstream -f -n '__fish_seen_subcommand_from why' -a '(__fish_complete_path)'`)
  return `${lines.join('\n')}\n`
}
